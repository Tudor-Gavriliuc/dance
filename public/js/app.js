/* ============================================
   SCHEDULE LOADER FROM JSON
   ============================================ */
let scheduleData = null;

function loadSchedule() {
    fetch('/data/schedule.json')
        .then(response => response.json())
        .then(data => {
            scheduleData = data;
            renderSchedule('kids_teens');
        })
        .catch(error => console.error('Error loading schedule:', error));
}

function renderSchedule(category) {
    if (!scheduleData) return;
    
    const schedule = scheduleData.schedule[category];
    const $container = $('.schedule__slots');
    const $buttons = $('.schedule__category-btn');
    
    if (!schedule) return;
    
    // Update active button
    $buttons.removeClass('active');
    $buttons.filter(`[data-category="${category}"]`).addClass('active');
    
    $container.empty();
    
    // Group by day
    const dayMap = {
        'luni': 1,
        'marti': 2,
        'miercuri': 3,
        'joi': 4,
        'vineri': 5,
        'sambata': 6,
        'duminica': 7
    };
    
    let allSlots = [];
    
    schedule.classes.forEach(dayClass => {
        if (dayClass.slots) {
            // Multiple classes on same day
            dayClass.slots.forEach(slot => {
                allSlots.push({
                    day: dayClass.day,
                    dayName: dayClass.dayName,
                    time: slot.time,
                    type: slot.type,
                    dayOrder: dayMap[dayClass.day] || 0,
                    timeOrder: slot.time.replace(':', '')
                });
            });
        } else {
            // Single class on day
            allSlots.push({
                day: dayClass.day,
                dayName: dayClass.dayName,
                time: dayClass.time,
                type: dayClass.type,
                dayOrder: dayMap[dayClass.day] || 0,
                timeOrder: dayClass.time.replace(':', '')
            });
        }
    });
    
    // Sort by day and time
    allSlots.sort((a, b) => {
        if (a.dayOrder !== b.dayOrder) return a.dayOrder - b.dayOrder;
        return a.timeOrder - b.timeOrder;
    });
    
    let currentDay = null;
    
    allSlots.forEach((slot, index) => {
        if (slot.day !== currentDay) {
            currentDay = slot.day;
            const dayHeader = `
                <div class="schedule__day-header">
                    <h3 class="schedule__day-title">${slot.dayName}</h3>
                </div>
            `;
            $container.append(dayHeader);
        }
        
        const html = `
            <div class="schedule__slot">
                <time class="schedule__time">${slot.time}</time>
                <strong class="schedule__class">${slot.type}</strong>
            </div>
        `;
        $container.append(html);
    });
    
    // Add single book button at the end
    const bookButton = `
        <div class="schedule__book-section">
            <a href="https://n1470867.alteg.io" target="_blank" class="schedule__book-btn">Rezervă o clasă</a>
        </div>
    `;
    $container.append(bookButton);
}

function initScheduleCategories() {
    $(document).on('click', '.schedule__category-btn', function() {
        const category = $(this).data('category');
        renderSchedule(category);
    });
}
