/* ============================================
   STATE & INITIALIZATION
   ============================================ */
let currentLanguage = localStorage.getItem('language') || 'ro';

$(document).ready(function() {
    console.log('Document ready - initializing...');
    initLanguage();
    console.log('Language initialized');
    initLanguageButtons();
    console.log('Language buttons initialized');
    initMobileMenu();
    console.log('Mobile menu initialized');
    loadSchedule();
    console.log('Schedule loaded');
    initScheduleCategories();
    console.log('Schedule categories initialized');
});

/* ============================================
   LANGUAGE FUNCTIONALITY
   ============================================ */
function initLanguage() {
    updateLanguage(currentLanguage);
    updateLanguageButtons();
}

function initLanguageButtons() {
    $('[data-lang]').on('click', function() {
        const lang = $(this).data('lang');
        currentLanguage = lang;
        localStorage.setItem('language', lang);
        updateLanguage(lang);
        updateLanguageButtons();
    });
}

function updateLanguage(lang) {
    $('html').attr('lang', lang);
    
    $('[data-i18n]').each(function() {
        const key = $(this).data('i18n');
        const text = translations[lang][key];
        
        if (text) {
            if (key === 'hero') {
                $(this).html(text);
            } else {
                $(this).text(text);
            }
        }
    });
}

function updateLanguageButtons() {
    $('[data-lang]').each(function() {
        if ($(this).data('lang') === currentLanguage) {
            $(this).addClass('active');
        } else {
            $(this).removeClass('active');
        }
    });
}

/* ============================================
   MOBILE MENU
   ============================================ */
function initMobileMenu() {
    // Use event delegation for toggle button (works even if DOM changes)
    $(document).on('click', '.header__nav-toggle', function(e) {
        e.preventDefault();
        e.stopPropagation();
        
        const $nav = $('.header__nav');
        const $toggle = $(this);
        
        // Toggle menu and button states
        if ($nav.hasClass('active')) {
            $nav.removeClass('active');
            $toggle.removeClass('active');
        } else {
            $nav.addClass('active');
            $toggle.addClass('active');
        }
    });
    
    // Close menu when a nav link is clicked
    $(document).on('click', '.header__link', function() {
        $('.header__nav').removeClass('active');
        $('.header__nav-toggle').removeClass('active');
    });
    
    // Close menu when clicking outside
    $(document).on('click', function(e) {
        const $toggle = $('.header__nav-toggle');
        const $nav = $('.header__nav');
        
        if (!$toggle.is(e.target) && !$toggle.has(e.target).length && !$nav.is(e.target) && !$nav.has(e.target).length) {
            $nav.removeClass('active');
            $toggle.removeClass('active');
        }
    });
}

